"""Generate the synchronous V05 element catalog from the reviewed manifest."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
MANIFEST = ROOT / 'docs/assets/set-review-v01/manifest.json'
OUTPUT = ROOT / 'docs/set-review-elements.js'


def catalog_source():
    text = MANIFEST.read_text(encoding='utf-8')
    manifest = json.loads(text)
    if manifest.get('assetVersion') != 'V05':
        raise ValueError('The reviewed V05 manifest is required')
    assets = []
    for scene in manifest['backgrounds']:
        for group, key in [('flowers', 'flowers'), ('decor', 'environment')]:
            for source in scene[key]:
                asset = {name: source[name] for name in ['id', 'name', 'src', 'preview', 'width', 'height', 'category', 'theme', 'sha256']}
                asset.update(file=source['id']+'.png', thumb=source['preview'], group=group, design=source.get('design'), color=source.get('color'), completeObject=True, transparent=True, stillOnly=True, lightingBaked=True, imageStyleVersion=76, setReviewVersion='V05', ready=True, kind='image')
                for name in ['designLabel', 'colorLabel']:
                    if name in source:
                        asset[name] = source[name]
                if not source['verification']['complete'] or not asset['id'].endswith('-V05'):
                    raise ValueError('Unreviewed element: ' + asset['id'])
                assets.append(asset)
    if len(assets) != 120 or len({a['id'] for a in assets}) != 120:
        raise ValueError('Expected 96 flowers and 24 environment elements')
    rows = ',\n'.join('    ' + json.dumps(a, ensure_ascii=False, separators=(',', ':')) for a in assets)
    digest = hashlib.sha256(text.encode('utf-8')).hexdigest()
    return f'''// Generated by build_set_review_elements.py; independent PNG metadata only.
(() => {{
  'use strict';
  const elements = window.jejuSetReviewElements = {{version:'V05',ready:false,manifestSha256:'{digest}',manifestHashEncoding:'UTF-8 LF',assets:[
{rows}
  ]}};
  const catalog = window.jejuFinalCatalog;
  if (!Array.isArray(catalog?.assets)) return;
  const ids = new Set(catalog.assets.map(a => a.id));
  for (const asset of elements.assets) {{
    if (ids.has(asset.id)) continue;
    catalog.assets.push(asset);
    ids.add(asset.id);
  }}
  elements.ready = true;
}})();
'''


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = catalog_source()
    if args.check:
        if OUTPUT.read_text(encoding='utf-8') != expected:
            raise ValueError('V05 element catalog differs from the current manifest')
    else:
        OUTPUT.write_text(expected, encoding='utf-8')
    print('PASS: synchronous V05 catalog contains 120 independent elements')
